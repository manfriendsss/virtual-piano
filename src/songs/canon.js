import { buildSong } from './buildSong.js';
import { makeMelody, evenNotes } from './helpers.js';

/**
 * 1) Canon in D — Johann Pachelbel (D Major, 76 BPM) — FULL VERSION
 * Ground bass (D - A - Bm - F#m - G - D - G - A) repeated under 16 successive
 * variations, from the slow opening theme through the famous running passages
 * to a quiet return of the theme and final cadence (~3:50).
 */
const SONG_CANON_IN_D = buildSong('canon', 'Canon in D', 76, ({ add }) => {
  const mel = makeMelody(add);
  const lhChords = [
    ['D3',  'A3',  'D4', 'F#3'], // D
    ['A2',  'E3',  'A3', 'C#4'], // A
    ['B2',  'F#3', 'B3', 'D4'],  // Bm
    ['F#2', 'C#3', 'F#3', 'A3'], // F#m
    ['G2',  'D3',  'G3', 'B3'],  // G
    ['D3',  'A3',  'D4', 'F#3'], // D
    ['G2',  'D3',  'G3', 'B3'],  // G
    ['A2',  'E3',  'A3', 'C#4'], // A
  ];

  const addLhCycle = (s, v = 0.56, style = 'arp') => {
    lhChords.forEach((arp, idx) => {
      const b = s + idx * 2;
      if (style === 'block') {
        add(b, arp[0], 1.9, 'LH', v + 0.04);
        add(b + 0.1, [arp[1], arp[3]], 1.8, 'LH', v - 0.04);
        return;
      }
      add(b + 0.0, arp[0], 1.85, 'LH', v + 0.06);
      add(b + 0.5, arp[1], 1.25, 'LH', v);
      add(b + 1.0, arp[2], 0.95, 'LH', v + 0.02);
      add(b + 1.5, arp[3], 0.55, 'LH', v - 0.03);
    });
  };

  // Var 1–2: the classic slow theme
  const V1 = evenNotes(['F#5', 'E5', 'D5', 'C#5', 'B4', 'A4', 'B4', 'C#5'], 2);
  const V2 = evenNotes(['D5', 'C#5', 'B4', 'A4', 'G4', 'F#4', 'G4', 'E4'], 2);
  // Var 3–4: flowing eighth notes
  const V3 = evenNotes(['D5', 'F#5', 'A5', 'G5', 'F#5', 'D5', 'F#5', 'E5',
    'D5', 'B4', 'D5', 'A5', 'G5', 'B5', 'A5', 'G5'], 1);
  const V4 = evenNotes(['F#5', 'D5', 'E5', 'C#5', 'D5', 'F#5', 'A5', 'A4',
    'B4', 'G4', 'A4', 'F#4', 'D4', 'D5', 'D5', 'C#5'], 1);
  // Var 5–6: sixteenth-note lines
  const V5 = evenNotes([
    'D5', 'C#5', 'D5', 'A4', 'C#5', 'A4', 'E4', 'F#4',
    'D4', 'D5', 'C#5', 'B4', 'C#5', 'F#5', 'A5', 'B5',
    'G5', 'F#5', 'E5', 'G5', 'F#5', 'E5', 'D5', 'C#5',
    'B4', 'A4', 'G4', 'F#4', 'E4', 'G4', 'F#4', 'E4',
  ], 0.5);
  const V6 = evenNotes([
    'F#5', 'A5', 'G5', 'F#5', 'E5', 'C#5', 'D5', 'E5',
    'F#5', 'D5', 'C#5', 'B4', 'C#5', 'A4', 'B4', 'C#5',
    'D5', 'B4', 'A4', 'G4', 'F#4', 'A4', 'D5', 'F#5',
    'G5', 'D5', 'B4', 'G5', 'E5', 'C#5', 'A4', 'C#5',
  ], 0.5);
  // Var 7: the famous running variation
  const V7 = [
    ['A5', 0.5, 0.86], ['F#5', 0.25], ['G5', 0.25], ['A5', 0.5, 0.86], ['F#5', 0.25], ['G5', 0.25],
    ['A5', 0.25, 0.84], ['A4', 0.25], ['B4', 0.25], ['C#5', 0.25], ['D5', 0.25], ['E5', 0.25], ['F#5', 0.25], ['G5', 0.25],
    ['F#5', 0.5, 0.84], ['D5', 0.25], ['E5', 0.25], ['F#5', 0.5, 0.84], ['F#4', 0.25], ['G4', 0.25],
    ['A4', 0.25], ['B4', 0.25], ['A4', 0.25], ['G4', 0.25], ['A4', 0.25], ['F#4', 0.25], ['G4', 0.25], ['A4', 0.25],
    ['G4', 0.5, 0.82], ['B4', 0.25], ['A4', 0.25], ['G4', 0.5, 0.82], ['F#4', 0.25], ['E4', 0.25],
    ['F#4', 0.25], ['E4', 0.25], ['D4', 0.25], ['E4', 0.25], ['F#4', 0.25], ['G4', 0.25], ['A4', 0.25], ['B4', 0.25],
    ['G4', 0.5, 0.84], ['B4', 0.25], ['A4', 0.25], ['B4', 0.5, 0.85], ['C#5', 0.25], ['D5', 0.25],
    ['A4', 0.25], ['B4', 0.25], ['C#5', 0.25], ['D5', 0.25], ['E5', 0.25], ['F#5', 0.25], ['G5', 0.25], ['A5', 0.25],
  ];
  // Var 8: running variation, second half
  const V8 = [
    ['F#5', 0.5, 0.86], ['D5', 0.25], ['E5', 0.25], ['F#5', 0.5, 0.86], ['E5', 0.25], ['D5', 0.25],
    ['E5', 0.25], ['C#5', 0.25], ['D5', 0.25], ['E5', 0.25], ['F#5', 0.25], ['E5', 0.25], ['D5', 0.25], ['C#5', 0.25],
    ['D5', 0.5, 0.84], ['B4', 0.25], ['C#5', 0.25], ['D5', 0.5, 0.84], ['F#4', 0.25], ['G4', 0.25],
    ['A4', 0.25], ['G4', 0.25], ['F#4', 0.25], ['G4', 0.25], ['A4', 0.25], ['B4', 0.25], ['C#5', 0.25], ['A4', 0.25],
    ['B4', 0.5, 0.84], ['D5', 0.25], ['C#5', 0.25], ['B4', 0.5, 0.84], ['A4', 0.25], ['G4', 0.25],
    ['A4', 0.25], ['G4', 0.25], ['F#4', 0.25], ['G4', 0.25], ['A4', 0.25], ['B4', 0.25], ['C#5', 0.25], ['D5', 0.25],
    ['B4', 0.5, 0.84], ['D5', 0.25], ['C#5', 0.25], ['D5', 0.5, 0.85], ['C#5', 0.25], ['B4', 0.25],
    ['C#5', 0.25], ['D5', 0.25], ['E5', 0.25], ['D5', 0.25], ['C#5', 0.25], ['D5', 0.25], ['B4', 0.25], ['C#5', 0.25],
  ];
  // Var 9: light detached (pizzicato-style) notes
  const V9 = ['F#5', 'F#5', 'E5', 'E5', 'D5', 'D5', 'C#5', 'C#5', 'B4', 'B4', 'A4', 'A4', 'B4', 'B4', 'C#5', 'C#5']
    .flatMap((n) => [[n, 0.55], [null, 0.45]]);
  // Var 10: theme in two voices (thirds)
  const V10 = [
    [['D5', 'F#5'], 2], [['C#5', 'E5'], 2], [['B4', 'D5'], 2], [['A4', 'C#5'], 2],
    [['G4', 'B4'], 2], [['F#4', 'A4'], 2], [['G4', 'B4'], 2], [['E4', 'C#5'], 2],
  ];
  // Var 11: grand chordal theme
  const V11 = [
    [['A4', 'D5', 'F#5'], 'F#5'], [['A4', 'C#5', 'E5'], 'E5'], [['F#4', 'B4', 'D5'], 'D5'], [['F#4', 'A4', 'C#5'], 'C#5'],
    [['D4', 'G4', 'B4'], 'B4'], [['F#4', 'A4'], 'A4'], [['D4', 'G4', 'B4'], 'B4'], [['E4', 'A4', 'C#5'], 'C#5'],
  ].flatMap(([tri, top]) => [[tri, 1.5], [top, 0.5]]);
  // Var 12: sparkling arpeggios
  const V12 = evenNotes([
    'D5', 'F#5', 'A5', 'D6', 'A5', 'F#5', 'D5', 'F#5',
    'C#5', 'E5', 'A5', 'C#6', 'A5', 'E5', 'C#5', 'E5',
    'B4', 'D5', 'F#5', 'B5', 'F#5', 'D5', 'B4', 'D5',
    'A4', 'C#5', 'F#5', 'A5', 'F#5', 'C#5', 'A4', 'C#5',
    'G4', 'B4', 'D5', 'G5', 'D5', 'B4', 'G4', 'B4',
    'F#4', 'A4', 'D5', 'F#5', 'D5', 'A4', 'F#4', 'A4',
    'G4', 'B4', 'D5', 'G5', 'B5', 'G5', 'D5', 'B4',
    'A4', 'C#5', 'E5', 'A5', 'C#6', 'A5', 'G5', 'E5',
  ], 0.25);

  // Introduction: ground bass alone
  addLhCycle(0, 0.48);
  let t = 16;

  const plan = [
    [V1, 0.74, 0.52], [V2, 0.76, 0.54], [V3, 0.78, 0.56], [V4, 0.80, 0.57],
    [V5, 0.80, 0.58], [V6, 0.80, 0.58], [V7, 0.82, 0.60], [V8, 0.82, 0.60],
    [V9, 0.78, 0.56], [V10, 0.80, 0.58], [V11, 0.86, 0.62], [V12, 0.84, 0.62],
    [V5, 0.84, 0.61], [V8, 0.84, 0.61], [V3, 0.70, 0.52], [V1, 0.64, 0.48, 'block'],
  ];
  plan.forEach(([items, rv, lv, style]) => {
    addLhCycle(t, lv, style || 'arp');
    mel(t, items, { vel: rv });
    t += 16;
  });

  // Final rolled D major cadence
  add(t, 'D3', 5.6, 'LH', 0.62);
  add(t + 0.15, 'A3', 5.4, 'LH', 0.54);
  add(t + 0.3, 'D4', 5.2, 'LH', 0.54);
  add(t + 0.45, ['F#4', 'A4', 'D5'], 5.0, 'RH', 0.70);
});

export default SONG_CANON_IN_D;
